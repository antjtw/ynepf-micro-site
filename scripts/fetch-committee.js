#!/usr/bin/env node
/* ==========================================================================
   fetch-committee.js — pull committee members from Contentful and write
   assets/data/committee-content.html. build.js inlines it into
   committee.html between the <!-- @cms:committee start/end --> markers.

   Content model (create in Contentful before running):

     committeeMember
       name           Symbol    required
       role           Symbol    required
       bio            Text      optional (plain paragraph, shown under name/role)
       photo          Media     optional (single asset)
       instagramUrl   Symbol    optional (full profile URL)
       group          Symbol    required, one of the four GROUPS values below
                                (set up as a Contentful "Short text, list of
                                predefined values" validation so editors get
                                a dropdown)
       order          Integer   required (sort position within its group)

   Requires CONTENTFUL_SPACE_ID and CONTENTFUL_DELIVERY_TOKEN. Skips
   cleanly, leaving existing content untouched, if they are not set.

   Run: node scripts/fetch-committee.js
   ========================================================================== */
const fs = require("fs");
const path = require("path");
const { isConfigured, fetchAllEntries } = require("./lib/contentful");

const OUT_FILE = path.join(__dirname, "..", "assets", "data", "committee-content.html");

// Contentful's `group` field value -> the section heading and lede already
// on the page. Order here also fixes the order sections render in.
const GROUPS = [
  {
    value: "Executive team",
    heading: "Executive team",
    lede: "The Executive Team sets the direction for the division and leads its day-to-day running.",
    headingAttrs: ' style="margin-top:0;"',
  },
  {
    value: "Supporting committee",
    heading: "Supporting committee",
    lede: "The Supporting Committee delivers the work behind our competitions, reporting to the directors.",
  },
  {
    value: "International referees",
    heading: "International referees",
    lede: "IPF referees who can officiate at all levels of competition, from a Novice to the IPF World Championships.",
  },
  {
    value: "National referees",
    heading: "National referees",
    lede: "Nationally qualified referees who can lead national competitions as Chief Referee and Jury members.",
  },
];

function escapeHtml(str) {
  return String(str ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function photoUrl(photoAsset) {
  const url = photoAsset?.fields?.file?.url;
  if (!url) return "assets/img/person-placeholder.png";
  return url.startsWith("//") ? `https:${url}` : url;
}

function renderMember(member) {
  const f = member.fields;
  const src = photoUrl(f.photo);
  const social = f.instagramUrl
    ? `\n        <a class="p-social" href="${escapeHtml(f.instagramUrl)}" aria-label="${escapeHtml(f.name)} on Instagram" target="_blank" rel="noopener"><svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><rect x="3" y="3" width="18" height="18" rx="5" stroke="currentColor" stroke-width="2"/><circle cx="12" cy="12" r="4" stroke="currentColor" stroke-width="2"/><circle cx="17.5" cy="6.5" r="1.2" fill="currentColor"/></svg></a>`
    : "";
  const blurb = f.bio ? `\n        <p class="p-blurb">${escapeHtml(f.bio)}</p>` : "";
  return `      <li class="person-card">
        <img class="photo" src="${escapeHtml(src)}" alt="" width="240" height="296">
        <div class="p-head">
        <p class="p-name">${escapeHtml(f.name)}</p>
        <p class="p-role">${escapeHtml(f.role)}</p>
        </div>${blurb}${social}
      </li>`;
}

async function main() {
  if (!isConfigured()) {
    console.log("Contentful not configured (CONTENTFUL_SPACE_ID / CONTENTFUL_DELIVERY_TOKEN missing) — skipping committee fetch.");
    return;
  }

  const members = await fetchAllEntries("committeeMember", { order: "fields.order" });

  const sections = GROUPS.map((group) => {
    const groupMembers = members.filter((m) => m.fields.group === group.value);
    if (groupMembers.length === 0) return "";
    const items = groupMembers.map(renderMember).join("\n");
    return `      <h2${group.headingAttrs || ""}>${escapeHtml(group.heading)}</h2>
      <p class="lede">${escapeHtml(group.lede)}</p>
      <ul class="carousel carousel-bleed" role="list">
${items}
      </ul>`;
  })
    .filter(Boolean)
    .join("\n\n");

  const out =
    "<!-- Generated by scripts/fetch-committee.js from Contentful — do not edit by hand. -->\n" +
    sections +
    "\n";

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out, "utf8");
  console.log(`Wrote ${members.length} committee members to ${path.relative(process.cwd(), OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
