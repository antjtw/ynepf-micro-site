#!/usr/bin/env node
/* ==========================================================================
   fetch-competitions.js — pull the competition calendar from Contentful and
   write assets/data/competitions-content.html. build.js inlines it into
   calendar.html between the <!-- @cms:competitions start/end --> markers.

   Content model (create in Contentful before running):

     competition
       name        Symbol     required
       summary     Text       required (one-line description under the title)
       notes       Symbol, list   optional (short bullet points, e.g. entry
                                   window, "volunteers may spend points")
       extraNote   RichText   optional (a second paragraph — announcements,
                                   entry requirements, may contain links/bold)
       tag         Symbol     optional (small badge, e.g. "Sponsor TBD")
       dateLabel   Symbol     required (free text so ranges like "24–25 Jan
                                   2026" and single dates both work)
       venue       Symbol     required
       lifterCap   Integer    optional
       order       Integer    required

   Requires CONTENTFUL_SPACE_ID and CONTENTFUL_DELIVERY_TOKEN. Skips
   cleanly, leaving existing content untouched, if they are not set.

   Run: node scripts/fetch-competitions.js
   ========================================================================== */
const fs = require("fs");
const path = require("path");
const { isConfigured, fetchAllEntries } = require("./lib/contentful");
const { renderRichText } = require("./lib/rich-text-html");

const OUT_FILE = path.join(__dirname, "..", "assets", "data", "competitions-content.html");

const ICONS = {
  calendar:
    '<svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><rect x="3" y="5" width="18" height="16" rx="2" stroke="currentColor" stroke-width="2"/><path d="M3 9h18M8 3v4M16 3v4" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>',
  pin: '<svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><path d="M12 21s7-6.3 7-11a7 7 0 1 0-14 0c0 4.7 7 11 7 11Z" stroke="currentColor" stroke-width="2"/><circle cx="12" cy="10" r="2.5" stroke="currentColor" stroke-width="2"/></svg>',
  people:
    '<svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><circle cx="9" cy="8" r="3" stroke="currentColor" stroke-width="2"/><path d="M3 20a6 6 0 0 1 12 0M16 6a3 3 0 0 1 0 6M21 20a6 6 0 0 0-4-5.6" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>',
};

function escapeHtml(str) {
  return String(str ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function renderEvent(entry) {
  const f = entry.fields;
  const tag = f.tag ? `\n              <span class="tag tag-position">${escapeHtml(f.tag)}</span>` : "";
  const notes = Array.isArray(f.notes) && f.notes.length
    ? `\n            <ul style="margin-top:var(--space-2);">
${f.notes.map((n) => `              <li>${escapeHtml(n)}</li>`).join("\n")}
            </ul>`
    : "";
  const extra = f.extraNote
    ? `\n            <div class="event-desc">${renderRichText(f.extraNote)}</div>`
    : "";
  const capacity = f.lifterCap ? `\n              <span>${ICONS.people}${f.lifterCap} lifters</span>` : "";

  return `        <li>
          <article class="event">
            <div class="event-head"><h2>${escapeHtml(f.name)}</h2>${tag}</div>
            <p class="event-desc">${escapeHtml(f.summary)}</p>${notes}${extra}
            <div class="event-meta">
              <span>${ICONS.calendar}${escapeHtml(f.dateLabel)}</span>
              <span>${ICONS.pin}${escapeHtml(f.venue)}</span>${capacity}
            </div>
          </article>
        </li>`;
}

async function main() {
  if (!isConfigured()) {
    console.log("Contentful not configured (CONTENTFUL_SPACE_ID / CONTENTFUL_DELIVERY_TOKEN missing) — skipping competitions fetch.");
    return;
  }

  const competitions = await fetchAllEntries("competition", { order: "fields.order" });
  const items = competitions.map(renderEvent).join("\n");

  const out =
    "<!-- Generated by scripts/fetch-competitions.js from Contentful — do not edit by hand. -->\n" +
    `      <ul class="event-list">\n${items}\n      </ul>\n`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out, "utf8");
  console.log(`Wrote ${competitions.length} competitions to ${path.relative(process.cwd(), OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
