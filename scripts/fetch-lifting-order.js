#!/usr/bin/env node
/* ==========================================================================
   fetch-lifting-order.js — pull the published lifting-order sheet and write
   assets/js/lifting-order-data.js as a plain static data file.

   Run by .github/workflows/lifting-order.yml on a schedule. Safe to run
   locally too: `node scripts/fetch-lifting-order.js`.
   ========================================================================== */
const https = require("https");
const fs = require("fs");
const path = require("path");

const CSV_URL =
  "https://docs.google.com/spreadsheets/d/e/2PACX-1vSALdLwOIW_nM6XEddf4Jp6AGuTJoVEtRLmswvp3kZu7UeqvKYbVRxOmaela5Ii_A/pub?gid=1870819385&single=true&output=csv";

const OUT_FILE = path.join(__dirname, "..", "assets", "js", "lifting-order-data.js");

function fetchCsv(url, redirects = 5) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if ([301, 302, 303, 307, 308].includes(res.statusCode) && res.headers.location && redirects > 0) {
          res.resume();
          resolve(fetchCsv(res.headers.location, redirects - 1));
          return;
        }
        if (res.statusCode !== 200) {
          reject(new Error(`Unexpected status ${res.statusCode} fetching sheet`));
          res.resume();
          return;
        }
        let data = "";
        res.setEncoding("utf8");
        res.on("data", (chunk) => (data += chunk));
        res.on("end", () => resolve(data));
      })
      .on("error", reject);
  });
}

// Minimal RFC 4180 CSV parser: handles quoted fields, embedded commas/newlines/"" escapes.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\r") {
      // ignore; \n below ends the row
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((f) => f.trim() !== ""));
}

function toNumberOrNull(v) {
  const n = parseFloat(v);
  return Number.isFinite(n) ? n : null;
}

async function main() {
  const csv = await fetchCsv(CSV_URL);
  const rows = parseCsv(csv);
  const [header, ...body] = rows;
  if (!header) throw new Error("Sheet returned no rows");

  const normalised = header.map((h) => h.trim().toLowerCase());
  const col = (name) => normalised.indexOf(name);

  const idx = {
    day: col("day"),
    session: col("session"),
    flight: col("flight"),
    name: col("name"),
    openIpf: col("open ipf"),
    instagram: col("instagram"),
    age: col("age"),
    class: col("class"),
    glp: col("glp"),
  };

  for (const [key, i] of Object.entries(idx)) {
    if (i === -1) throw new Error(`Expected column not found in sheet: "${key}"`);
  }

  const lifters = body
    .map((r) => ({
      day: toNumberOrNull(r[idx.day]),
      session: toNumberOrNull(r[idx.session]),
      flight: (r[idx.flight] || "").trim(),
      name: (r[idx.name] || "").trim(),
      openIpf: (r[idx.openIpf] || "").trim(),
      instagram: (r[idx.instagram] || "").trim().replace(/^@/, ""),
      age: (r[idx.age] || "").trim(),
      class: (r[idx.class] || "").trim(),
      glp: toNumberOrNull(r[idx.glp]),
    }))
    .filter((l) => l.name);

  const payload = { generatedAt: new Date().toISOString(), lifters };
  const out =
    "// Generated by scripts/fetch-lifting-order.js — do not edit by hand.\n" +
    "// Source: published Google Sheet CSV (see CSV_URL in that script).\n" +
    "window.LIFTING_ORDER_DATA = " +
    JSON.stringify(payload, null, 2) +
    ";\n";

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, out, "utf8");
  console.log(`Wrote ${lifters.length} lifters to ${path.relative(process.cwd(), OUT_FILE)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
